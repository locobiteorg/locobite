package customers

import (
	"strings"
	"unicode"
)

// displayNameFromIdentifier builds a human name from the login identifier.
// Email OTP currently stores the address in customers.phone; using the last
// four characters produced names like "Traveller .com".
func displayNameFromIdentifier(id string) string {
	id = strings.TrimSpace(id)
	if at := strings.IndexByte(id, '@'); at > 0 {
		local := id[:at]
		local = strings.NewReplacer(".", " ", "_", " ", "-", " ", "+", " ").Replace(local)
		parts := strings.Fields(local)
		for i, p := range parts {
			parts[i] = titleWord(p)
		}
		if len(parts) == 0 {
			return "Traveller"
		}
		return strings.Join(parts, " ")
	}
	last := id
	if len(id) >= 4 {
		last = id[len(id)-4:]
	}
	return "Traveller " + last
}

func titleWord(s string) string {
	s = strings.ToLower(s)
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func isAutoGeneratedName(name string) bool {
	return strings.HasPrefix(strings.TrimSpace(name), "Traveller")
}
